create sequence if not exists public.complaint_number_seq;

create table if not exists public.complaints (
  id bigint generated by default as identity primary key,
  tracking_code text not null unique default ('LR-' || to_char(current_date, 'YYYY') || '-' || lpad(nextval('public.complaint_number_seq')::text, 8, '0')),
  created_at timestamptz not null default now(),
  consumer_name text not null,
  document_type text not null check (document_type in ('DNI', 'CE', 'PASAPORTE', 'RUC')),
  document_number text not null,
  consumer_address text not null,
  phone text not null,
  email text not null,
  is_minor boolean not null default false,
  guardian_name text,
  guardian_document text,
  item_type text not null check (item_type in ('PRODUCTO', 'SERVICIO')),
  item_description text not null,
  amount numeric(12,2) not null check (amount >= 0),
  complaint_type text not null check (complaint_type in ('RECLAMO', 'QUEJA')),
  detail text not null,
  consumer_request text not null,
  provider_legal_name text not null,
  provider_ruc char(11) not null,
  provider_address text not null,
  provider_actions text,
  status text not null default 'PENDIENTE' check (status in ('PENDIENTE', 'EN_PROCESO', 'RESPONDIDO')),
  responded_at timestamptz,
  constraint guardian_required_for_minor check (not is_minor or (guardian_name is not null and guardian_document is not null))
);

alter table public.complaints enable row level security;
revoke all on table public.complaints from anon, authenticated;
revoke all on sequence public.complaints_id_seq from anon, authenticated;
revoke all on sequence public.complaint_number_seq from anon, authenticated;
grant all on table public.complaints to service_role;
grant usage, select on sequence public.complaints_id_seq to service_role;
grant usage, select on sequence public.complaint_number_seq to service_role;

comment on column public.complaints.provider_actions is 'Acciones u observaciones comunicadas por el proveedor al responder la hoja.';
