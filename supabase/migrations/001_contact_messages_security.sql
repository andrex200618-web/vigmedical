-- Ejecutar en Supabase antes de activar el formulario en producción.
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  nombres text not null check (char_length(nombres) between 2 and 80),
  apellidos text not null check (char_length(apellidos) between 2 and 80),
  email text not null check (char_length(email) <= 254),
  telefono text not null check (char_length(telefono) between 7 and 20),
  mensaje text not null check (char_length(mensaje) between 10 and 2000),
  created_at timestamptz not null default now()
);

alter table public.contact_messages enable row level security;

-- El navegador no puede leer ni escribir mensajes directamente. La Route
-- Handler usa exclusivamente la clave service_role privada del servidor.
revoke all on table public.contact_messages from anon, authenticated;
revoke all on sequence public.contact_messages_id_seq from anon, authenticated;
grant all on table public.contact_messages to service_role;
grant usage, select on sequence public.contact_messages_id_seq to service_role;

-- Contador distribuido para despliegues serverless como Vercel. El identificador
-- recibido es un HMAC de la IP; la dirección original nunca se almacena.
create table if not exists public.contact_rate_limits (
  identifier text primary key,
  window_started_at timestamptz not null default now(),
  request_count integer not null default 1 check (request_count > 0)
);

alter table public.contact_rate_limits enable row level security;
revoke all on table public.contact_rate_limits from anon, authenticated;
grant all on table public.contact_rate_limits to service_role;

create or replace function public.check_contact_rate_limit(
  p_identifier text,
  p_window_seconds integer,
  p_max_requests integer
)
returns table (allowed boolean, retry_after integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  current_row public.contact_rate_limits%rowtype;
  current_time timestamptz := clock_timestamp();
begin
  if p_window_seconds < 1 or p_max_requests < 1 or char_length(p_identifier) <> 64 then
    raise exception 'Invalid rate-limit arguments';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_identifier, 0));

  select * into current_row
  from public.contact_rate_limits
  where identifier = p_identifier
  for update;

  if not found or current_row.window_started_at + make_interval(secs => p_window_seconds) <= current_time then
    insert into public.contact_rate_limits (identifier, window_started_at, request_count)
    values (p_identifier, current_time, 1)
    on conflict (identifier) do update
      set window_started_at = excluded.window_started_at,
          request_count = 1;
    return query select true, 0;
    return;
  end if;

  update public.contact_rate_limits
  set request_count = request_count + 1
  where identifier = p_identifier;

  return query select
    current_row.request_count < p_max_requests,
    greatest(1, ceil(extract(epoch from (
      current_row.window_started_at + make_interval(secs => p_window_seconds) - current_time
    )))::integer);
end;
$$;

revoke all on function public.check_contact_rate_limit(text, integer, integer) from public, anon, authenticated;
grant execute on function public.check_contact_rate_limit(text, integer, integer) to service_role;

